/**
 * Bundle the native read-engine worker for Electron.
 *
 * Bundles `client/src/workers/engine-node-worker.ts` (+ engine-core, adapter,
 * and the self-test harness it dynamically imports) into a single CommonJS file
 * at `electron/engine/engine-worker.bundle.cjs`. The native `better-sqlite3`
 * addon stays EXTERNAL — it is loaded at runtime from node_modules (dev) or the
 * asarUnpack'd location (packaged), never inlined.
 *
 * Invoked by scripts/electron-dev.sh (before the dev server) and
 * scripts/electron-build.sh (before electron-builder packages the app) so the
 * bundle is always fresh before main.cjs spawns the worker. electron-builder
 * itself does NOT run this, so the release script must call it explicitly.
 *
 * Usage: node scripts/build-native-engine.mjs
 */
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'client/src/workers/engine-node-worker.ts');
const outfile = resolve(root, 'electron/engine/engine-worker.bundle.cjs');

mkdirSync(dirname(outfile), { recursive: true });

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  // Native addon + Node built-ins resolve at runtime, never inlined.
  external: ['better-sqlite3'],
  // Keep IndexedDB-only deps out: the worker never touches the browser side.
  banner: { js: '/* AUTO-GENERATED by scripts/build-native-engine.mjs — do not edit. */' },
  logLevel: 'info',
  sourcemap: true,
  minify: false,
});

console.log(`Built ${outfile}`);
