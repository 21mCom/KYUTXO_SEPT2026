// Guards the Proof of Funds content fingerprint against silent drift.
//
// The SHA-256 fingerprint printed in the PDF's Document Integrity section is
// computed from the canonical payload built in pof-pdf-data.ts. After the
// section-module refactor, a change to any module could accidentally change
// (or stop covering) what the fingerprint hashes. This suite feeds fixed
// params into computePofPdfData and asserts:
//   1. the EXACT canonical payload lines, and
//   2. that the reported fingerprint hex equals an independently computed
//      SHA-256 of that exact payload.
// Any change to the canonical line structure must be made deliberately here.
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { createHash } from "node:crypto";
import { computePofPdfData } from "./pof-pdf-data";
import { KYUTXO_APP_VERSION } from "./declaration-prefs";
import type { UsePofPdfBuilderParams } from "./pof-pdf-context";

const FIXED_NOW = "2026-07-28T12:00:00.000Z";

const ADDR_VERIFIED = "bc1qtestaddr000000000000000000000000000001";
const ADDR_UNVERIFIED = "1TestAddrTwo1111111111111111111111";

